/**
 * Renders `src/spec/sections.ts`. Pure, so that `spec:check` can compare the
 * committed file with a fresh rendering without running the writer.
 *
 * Only the numbered headings go in. They are the ones a citation may name, and
 * they are all the compiler ever reads — the unnumbered ones exist for spec.md
 * to link to, which `spec:check` validates against the document itself.
 */
import { parseSpec } from "./parse.js";

const HEADER = `// GENERATED by \`npm run spec:sections\` from spec.md. Do not edit.
//
// A section's slug is its identity; its number is where it happens to sit
// today. Cite a section by slug and a renumber cannot reach the citation.

export interface SpecSection {
  readonly number: string;
  readonly title: string;
}
`;

const FOOTER = `
/**
 * Every section a diagnostic or a comment may cite. Because this is a union of
 * literals, a citation that names a section spec.md does not have fails to
 * compile.
 */
export type SpecId = keyof typeof SPEC_SECTIONS;
`;

export function renderSections(): string {
  const rows = parseSpec()
    .headings.filter((h) => h.number !== null)
    .map(
      (h) =>
        `  ${JSON.stringify(h.slug)}: ` +
        `{ number: ${JSON.stringify(h.number)}, title: ${JSON.stringify(h.title)} },`,
    );
  return `${HEADER}
export const SPEC_SECTIONS = {
${rows.join("\n")}
} as const satisfies Record<string, SpecSection>;
${FOOTER}`;
}
