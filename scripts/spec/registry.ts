/**
 * Renders `src/spec/sections.ts`. Pure, so that `spec:check` can compare the
 * committed file with a fresh rendering without running the writer.
 */
import { parseSpec } from "./parse.js";

const HEADER = `// GENERATED by \`npm run spec:sections\` from spec.md. Do not edit.
//
// A section's slug is its identity; its number is where it happens to sit
// today. Cite a section by slug and a renumber cannot reach the citation.

export interface SpecSection {
  readonly slug: string;
  /** \`"7.8"\`. Null for the title and the unnumbered \`####\` headings. */
  readonly number: string | null;
  readonly title: string;
  readonly level: 1 | 2 | 3 | 4;
}
`;

const FOOTER = `
/** Every heading in spec.md. */
export type SpecSlug = keyof typeof SPEC_SECTIONS;

/**
 * The headings that carry a number, and so are the ones a diagnostic or a
 * comment may cite. Because this is a union of literals, a citation that names
 * a section spec.md does not have fails to compile.
 */
export type SpecId = {
  [K in SpecSlug]: (typeof SPEC_SECTIONS)[K]["number"] extends string ? K : never;
}[SpecSlug];
`;

export function renderSections(): string {
  const doc = parseSpec();
  const rows = doc.headings.map((h) => {
    const number = h.number === null ? "null" : JSON.stringify(h.number);
    return (
      `  ${JSON.stringify(h.slug)}: { slug: ${JSON.stringify(h.slug)}, ` +
      `number: ${number}, title: ${JSON.stringify(h.title)}, level: ${h.level} },`
    );
  });
  return `${HEADER}
export const SPEC_SECTIONS = {
${rows.join("\n")}
} as const satisfies Record<string, SpecSection>;
${FOOTER}`;
}

