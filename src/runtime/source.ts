/**
 * The BlueScript source of an endpoint's `__runtime.bs` (spec §runtime-files):
 * the core helpers, which every program may call (spec §nothing,
 * §and-or-helpers, §copy-array-helper), and then, when `dyn` is set, the
 * dynamic-location runtime — the representation of dynamically located values
 * and the operations on them (spec §dyn-runtime–§dyn-print).
 *
 * Every endpoint gets the same text except for the header comment that names
 * it and, in the dynamic-location runtime, `__here`. The location constants
 * the dynamic-location runtime opens with number `endpoints` in order
 * (spec §location-and-kind-codes), so every endpoint's file must be generated
 * from the same list. The communication API and `print` are not here; they
 * come from BlueScript's standard library, as for every program
 * (spec §runtime-support-functions).
 *
 * Unverified BlueScript behaviour this relies on is listed in
 * spec §unverified-bluescript-assumptions.
 *
 * A profiling build (`options.profile`) puts a third part first and counts
 * events in the other two (spec §profiling-build); without it, nothing of
 * that is in the text.
 */
export function runtimeSource(
  endpoint: string,
  endpoints: readonly string[],
  dyn: boolean,
  options: BuildOptions = {},
): string {
  if (dyn && !endpoints.includes(endpoint)) {
    throw new Error(`internal error: runtime for ${endpoint}, which is not among ${endpoints.join(", ")}`);
  }
  const probe = options.profile === true ? PROFILING : PLAIN;
  return [
    `// ChoreoBS runtime for ${endpoint} (spec §runtime-support-functions).`,
    `// Generated by the compiler; every endpoint's copy differs only in ${dyn ? "__here and " : ""}this comment.`,
    ...(options.profile === true ? ["// Profiling build (spec §profiling-build).", "", profilingPart()] : [""]),
    nothingHelpers(),
    logicalHelpers(),
    copyHelper(probe),
    ...(dyn ? dynRuntime(endpoint, endpoints, probe) : []),
  ].join("\n");
}

/** The second part of the file, for a program that uses `dyn` (spec §dyn-runtime). */
function dynRuntime(endpoint: string, endpoints: readonly string[], p: Probe): string[] {
  return [
    codes(endpoints),
    locationVariables(p),
    LOCATION_ERROR,
    dynValue(p),
    locationFunctions(endpoint, endpoints, p),
    ...(p === PROFILING ? [PROFILE_OP_FUNCTION] : []),
    injectAndCast(p),
    ...entries(DYN_BINARY).map(([operator, name]) => binaryFunction(operator, name, p)),
    ...entries(DYN_UNARY).map(([operator, name]) => unaryFunction(operator, name, p)),
    ...entries(DYN_CONVERSION).map(([target, name]) => conversionFunction(target, name, p)),
    copyPayload(p),
    dispatch(p),
    transfer(p),
    arrayOperations(p),
    ARRAY_NEW,
    ARRAY_APPEND,
    dynPrint(p),
  ];
}

// --- §profiling-build --------------------------------------------------------

/**
 * What the profiling build adds to the text of the other two parts. Every
 * statement it returns is whole lines that end in a newline, placed where a
 * line starts, so the ordinary build's {@link PLAIN} leaves the text exactly
 * as it was.
 */
interface Probe {
  /** `key` plus one, indented by `indent`. */
  count(key: CounterKey, indent?: number): string;
  /** A dynamic operation of `category` at the location in `loc`. */
  op(category: OpCategory): string;
  /** The function to call for the communication API function `api`. */
  comm(api: string): string;
}

const PLAIN: Probe = {
  count: () => "",
  op: () => "",
  comm: (api) => api,
};

const PROFILING: Probe = {
  count: (key, indent = 2) => `${" ".repeat(indent)}${increment(profileVariable(key))}\n`,
  op: (category) => `${PROFILING.count(`op_${category}`)}  ${PROFILE_OP}(loc);\n`,
  comm: profiledFunction,
};

function increment(variable: string): string {
  return `${variable} = ${variable} + 1;`;
}

/**
 * The part a profiling build puts first: the counters, the communication
 * wrappers, and `__profReport`. The counters are primitives, which the
 * collector does not trace, and are not exported: only this file assigns them.
 */
function profilingPart(): string {
  const counters = PROFILE_COUNTERS.map(
    ({ key, type }) => `let ${profileVariable(key)}: ${type} = ${type === "float" ? "0.0" : "0"};`,
  ).join("\n");
  const wrappers = ALL_COMM_KINDS.flatMap((kind) => [sendWrapper(kind), receiveWrapper(kind)]);
  const broadcasts = ALL_COMM_KINDS.map(broadcastWrapper);
  const report = [
    `  print(${JSON.stringify(PROFILE_MARKER)});`,
    `  print(${PROFILE_FORMAT_VERSION});`,
    `  print(${PROFILE_COUNTERS.length});`,
    ...PROFILE_COUNTERS.map(({ key }) => `  print(${profileVariable(key)});`),
  ].join("\n");
  return [
    `${counters}\n`,
    ...wrappers,
    ...broadcasts,
    `export function ${PROFILE_REPORT}(): void {\n${report}\n}\n`,
  ].join("\n");
}

/** Adds the time since `t0` to `role`'s total, and one to its count. */
function account(role: "send" | "receive" | "broadcast"): string {
  const ms = profileVariable(`${role}_ms`);
  return `  ${ms} = ${ms} + (performanceNow() - t0);
  ${increment(profileVariable(`${role}_n`))}`;
}

function sendWrapper(kind: CommKind): string {
  const api = sendFunction(kind);
  return `export function ${profiledFunction(api)}(to: string, tag: string, v: ${COMM_VALUE_TYPE[kind]}): void {
  const t0 = performanceNow();
  ${api}(to, tag, v);
${account("send")}
}
`;
}

function receiveWrapper(kind: CommKind): string {
  const api = receiveFunction(kind);
  const type = COMM_VALUE_TYPE[kind];
  return `export function ${profiledFunction(api)}(from: string, tag: string): ${type} {
  const t0 = performanceNow();
  const v: ${type} = ${api}(from, tag);
${account("receive")}
  return v;
}
`;
}

function broadcastWrapper(kind: CommKind): string {
  const api = broadcastFunction(kind);
  return `export function ${profiledFunction(api)}(tag: string, v: ${COMM_VALUE_TYPE[kind]}): void {
  const t0 = performanceNow();
  ${api}(tag, v);
${account("broadcast")}
}
`;
}

/**
 * Where a dynamic operation ran, by the location its operands were unified to:
 * this endpoint, `every`, still unbound — each of which computes the payload —
 * or another endpoint, which skips it. It compares the codes itself, so the
 * dispatch counters see only the operation's own checks.
 */
const PROFILE_OP_FUNCTION = `function ${PROFILE_OP}(loc: integer): void {
${ifChain(
  [
    ["loc === __here", `    ${increment(profileVariable("op_here"))}`],
    [`loc === ${LOC_EVERY}`, `    ${increment(profileVariable("op_every"))}`],
    [`loc === ${LOC_DYN}`, `    ${increment(profileVariable("op_unbound"))}`],
  ],
  `    ${increment(profileVariable("op_skip"))}`,
)}
}
`;

/** `Object.entries` for a table keyed by string literals, in its key order. */
function entries<K extends string, V>(table: Readonly<Record<K, V>>): (readonly [K, V])[] {
  return Object.entries(table) as [K, V][];
}

/**
 * `if (kind === __kind_k1) { … } else if (kind === __kind_k2) { … }` over
 * `kinds`, each branch's body indented by four, closed by `otherwise` as an
 * `else` when given.
 */
function kindBranches(
  kinds: readonly CommKind[],
  branch: (kind: CommKind) => string,
  otherwise?: string,
): string {
  return ifChain(
    kinds.map((kind) => [`kind === ${kindConstantName(kind)}`, branch(kind)]),
    otherwise,
  );
}

/**
 * `if (c1) { … } else if (c2) { … }` at the top of a function body, from
 * condition–body pairs whose bodies are indented by four, closed by
 * `otherwise` as an `else` when given.
 */
function ifChain(arms: readonly (readonly [string, string])[], otherwise?: string): string {
  const opened = arms.map(
    ([condition, body], i) => `  ${i === 0 ? "if" : "} else if"} (${condition}) {\n${body}`,
  );
  const close = otherwise === undefined ? "  }" : `  } else {\n${otherwise}\n  }`;
  return [...opened, close].join("\n");
}

// --- §nothing ----------------------------------------------------------------

/**
 * `__nothing1` to `__nothing5`. The arguments are already evaluated by the time
 * the body runs, which is all `nothing(...)` asks of them; `any` takes a value
 * of every type, as BlueScript has neither rest nor type parameters.
 */
function nothingHelpers(): string {
  return NOTHING_HELPERS.map((name, i) => {
    const params = Array.from({ length: i + 1 }, (_, j) => `a${j + 1}: any`).join(", ");
    return `export function ${name}(${params}): null {
  return null;
}
`;
  }).join("\n");
}

// --- §and-or-helpers ---------------------------------------------------------

/**
 * `__and` and `__or`. Both arguments are already evaluated, so BlueScript's
 * short circuit in the body changes nothing.
 */
function logicalHelpers(): string {
  return entries(LOGICAL_HELPERS)
    .map(([operator, name]) => `export function ${name}(a: boolean, b: boolean): boolean {
  return a ${operator} b;
}
`)
    .join("\n");
}

// --- §copy-array-helper ------------------------------------------------------

/**
 * `__copyArray`: BlueScript's copying constructor, given an array, makes a new
 * `any[]` with the same elements. Shallow is enough, since no element is an
 * array (spec §copy-array-helper).
 */
function copyHelper(p: Probe): string {
  return `export function ${COPY_ARRAY_HELPER}(v: any[]): any[] {
${p.count("copy_array")}  return new Array<any>(v);
}
`;
}

// --- §location-and-kind-codes ------------------------------------------------

/**
 * The location and kind constants, and `__locationName`, which turns a
 * location's code back into the name the communication API and error messages
 * use. Its last `return` is never reached; BlueScript wants every path of a
 * function with a result to end in one.
 */
function codes(endpoints: readonly string[]): string {
  const declare = ({ name, code }: RuntimeConstant): string =>
    `export const ${name}: integer = ${code};`;
  const locations = locationConstants(endpoints);
  const names = ifChain(
    locations.map(({ name, location }) => [`loc === ${name}`, `    return ${JSON.stringify(location)};`]),
  );
  return `${locations.map(declare).join("\n")}

${KIND_CONSTANTS.map(declare).join("\n")}

function __locationName(loc: integer): string {
${names}
  return "";
}
`;
}

// --- §location-variables -----------------------------------------------------

function locationVariables(p: Probe): string {
  return `export class __LocVar {
  parent: __LocVar;
  bound: integer;
  rank: integer;

  constructor(bound: integer) {
    this.parent = this;
    this.bound = bound;
    this.rank = 0;
${p.count("locvar_new", 4)}  }
}

function __root(v: __LocVar): __LocVar {
  let r: __LocVar = v;
  while (r.parent !== r) {
    r = r.parent;
${p.count("root_steps", 4)}  }
  return r;
}

export function __find(v: __LocVar): integer {
${p.count("find")}  return __root(v).bound;
}

export function __unify(a: __LocVar, b: __LocVar): integer {
${p.count("unify")}  const ra = __root(a);
  const rb = __root(b);
  if (ra === rb) {
    return ra.bound;
  }
  if (ra.bound !== ${LOC_DYN} && rb.bound !== ${LOC_DYN}) {
    if (ra.bound !== rb.bound) {
      __locationError(ra.bound, rb.bound);
    }
    return ra.bound;
  }
  let top: __LocVar = ra;
  let sub: __LocVar = rb;
  if (rb.bound !== ${LOC_DYN} || (ra.bound === ${LOC_DYN} && rb.rank > ra.rank)) {
    top = rb;
    sub = ra;
  }
  sub.parent = top;
  if (sub.rank === top.rank) {
    top.rank = top.rank + 1;
  }
  return top.bound;
}

export function __bind(v: __LocVar, loc: integer): void {
${p.count("bind")}  const r = __root(v);
  if (r.bound === ${LOC_DYN}) {
    r.bound = loc;
  } else if (r.bound !== loc) {
    __locationError(r.bound, loc);
  }
}
`;
}

// --- §location-errors --------------------------------------------------------

// Stops this endpoint with a runtime error naming the two locations that
// clashed, through BlueScript's C function `runtime_error`, embedded with a
// `code` template. Every endpoint adds the same constraints in the same order,
// so every endpoint stops at the same operation.
const LOCATION_ERROR = `export function __locationError(a: integer, b: integer): void {
  const message = "location error: " + __locationName(a) + " and " + __locationName(b);
  code\`runtime_error(gc_string_to_cstr(\${message}));\`;
}
`;

// --- §dyn-val ----------------------------------------------------------------

function dynValue(p: Probe): string {
  return `export class __DynVal {
  payload: any;
  loc: __LocVar;

  constructor(payload: any, loc: __LocVar) {
    this.payload = payload;
    this.loc = loc;
${p.count("dynval_new", 4)}  }
}

export function __dynUnbound(payload: any): __DynVal {
${p.count("unbound")}  return new __DynVal(payload, new __LocVar(${LOC_DYN}));
}

export function __dynAt(payload: any, loc: integer): __DynVal {
  return new __DynVal(payload, new __LocVar(loc));
}
`;
}

// --- §location-functions -----------------------------------------------------

/**
 * `__holdsPayload` is called by every dynamic operation, so it compares the
 * codes itself rather than through `__isEvery` and `__isHere`.
 */
function locationFunctions(endpoint: string, endpoints: readonly string[], p: Probe): string {
  const here = locationConstants(endpoints).find((c) => c.location === endpoint)!.name;
  return `export const __here: integer = ${here};

export function __isHere(loc: integer): boolean {
${p.count("is_here")}  return loc === __here;
}

export function __isEvery(loc: integer): boolean {
${p.count("is_every")}  return loc === ${LOC_EVERY};
}

export function __holdsPayload(loc: integer): boolean {
${p.count("holds")}  return loc === ${LOC_DYN} || loc === ${LOC_EVERY} || loc === __here;
}
`;
}

// --- §inject-and-cast --------------------------------------------------------

function injectAndCast(p: Probe): string {
  return `export function __inject(payload: any, loc: integer): __DynVal {
${p.count("inject")}  return __dynAt(payload, loc);
}

export function __cast(v: __DynVal, loc: integer): any {
${p.count("cast")}  __bind(v.loc, loc);
  if (__isHere(loc) || __isEvery(loc)) {
    return v.payload;
  } else {
    return null;
  }
}
`;
}

// --- §dyn-operators ----------------------------------------------------------

/**
 * The operator applied to the two payloads as written (spec §dyn-operators). For
 * `&&` and `||` both operands are already evaluated, so BlueScript's short
 * circuit changes nothing.
 */
function binaryFunction(operator: BinaryOperator, name: DynRuntimeFunction, p: Probe): string {
  return `export function ${name}(left: __DynVal, right: __DynVal): __DynVal {
  const loc = __unify(left.loc, right.loc);
${p.op("arith")}  if (__holdsPayload(loc)) {
    return new __DynVal(left.payload ${operator} right.payload, left.loc);
  } else {
    return new __DynVal(null, left.loc);
  }
}
`;
}

function unaryFunction(operator: UnaryOperator, name: DynRuntimeFunction, p: Probe): string {
  return `export function ${name}(v: __DynVal): __DynVal {
  const loc = __find(v.loc);
${p.op("arith")}  if (__holdsPayload(loc)) {
    return new __DynVal(${operator}v.payload, v.loc);
  } else {
    return new __DynVal(null, v.loc);
  }
}
`;
}

// --- §dyn-numeric-conversion -------------------------------------------------

/**
 * A conversion to `target` from the other numeric type. The payload is brought
 * back to its static type before BlueScript's own `as` converts it, as in a
 * static conversion: `as integer` rejects an `any` that holds a float
 * (spec §numeric-conversion-code-generation).
 */
function conversionFunction(target: NumericType, name: DynRuntimeFunction, p: Probe): string {
  const source: NumericType = target === "float" ? "integer" : "float";
  return `export function ${name}(v: __DynVal): __DynVal {
  const loc = __find(v.loc);
${p.op("arith")}  if (__holdsPayload(loc)) {
    return new __DynVal((v.payload as ${source}) as ${target}, v.loc);
  } else {
    return new __DynVal(null, v.loc);
  }
}
`;
}

// --- §dyn-transfer-runtime ---------------------------------------------------

function copyPayload(p: Probe): string {
  return `function __copyPayload(kind: integer, v: any): any {
${p.count("kind_dispatch")}${kindBranches([ARRAY_COMM_KIND], (kind) => `    return ${copyFunction(kind)}(v);`, "    return v;")}
}
`;
}

/**
 * `__sendAny` / `__receiveAny` / `__broadcastAny`: the communication API chosen
 * by the static `kind` the compiler passes (spec §dynamic-transfer). The
 * receiving side has no payload to look at, which is why the kind is passed
 * rather than read off the value. The peer is passed by name, as the API takes
 * it.
 */
function dispatch(p: Probe): string {
  const branches = (call: (kind: CommKind) => string): string =>
    kindBranches(ALL_COMM_KINDS, (kind) => `    ${call(kind)}`);
  return `function __sendAny(to: string, tag: string, kind: integer, v: any): void {
${p.count("kind_dispatch")}${branches((kind) => `${p.comm(sendFunction(kind))}(to, tag, v);`)}
}

function __receiveAny(from: string, tag: string, kind: integer): any {
${p.count("kind_dispatch")}${branches((kind) => `return ${p.comm(receiveFunction(kind))}(from, tag);`)}
  return null;
}

function __broadcastAny(tag: string, kind: integer, v: any): void {
${p.count("kind_dispatch")}${branches((kind) => `${p.comm(broadcastFunction(kind))}(tag, v);`)}
}
`;
}

/**
 * `__dynTransfer`, in two steps (spec §dyn-transfer-runtime): the owner of the
 * source communicates when the destination is not its own — a broadcast where
 * every endpoint is to hold the payload, a send otherwise — and then each
 * endpoint makes the one fresh result. `__dynAt(x, __loc_dyn)` is an unbound
 * value, so no case for `dyn` is needed.
 */
function transfer(p: Probe): string {
  return `export function __dynTransfer(tag: string, kind: integer, to: integer, v: __DynVal): __DynVal {
${p.count("transfer")}  const from = __find(v.loc);
  if (__isHere(from) && !__isHere(to)) {
    if (__holdsPayload(to)) {
${p.count("transfer_broadcast", 6)}      __broadcastAny(tag, kind, v.payload);
    } else {
${p.count("transfer_send", 6)}      __sendAny(__locationName(to), tag, kind, v.payload);
    }
  }
  if (!__holdsPayload(to)) {
${p.count("transfer_none", 4)}    return __dynAt(null, to);
  } else if (__holdsPayload(from)) {
${p.count("transfer_copy", 4)}    return __dynAt(__copyPayload(kind, v.payload), to);
  } else {
${p.count("transfer_receive", 4)}    return __dynAt(__receiveAny(__locationName(from), tag, kind), to);
  }
}
`;
}

// --- §dyn-array-operations ---------------------------------------------------

function arrayOperations(p: Probe): string {
  return `export function __dynArrayGet(arr: __DynVal, i: __DynVal): __DynVal {
  const loc = __unify(arr.loc, i.loc);
${p.op("array")}  if (__holdsPayload(loc)) {
    return new __DynVal(arr.payload[i.payload], arr.loc);
  } else {
    return new __DynVal(null, arr.loc);
  }
}

export function __dynArraySet(arr: __DynVal, i: __DynVal, v: __DynVal): void {
  __unify(arr.loc, i.loc);
  const loc = __unify(i.loc, v.loc);
${p.op("array")}  if (__holdsPayload(loc)) {
    arr.payload[i.payload] = v.payload;
  }
}

export function __dynArrayPush(arr: __DynVal, v: __DynVal): void {
  const loc = __unify(arr.loc, v.loc);
${p.op("array")}  if (__holdsPayload(loc)) {
    arr.payload.push(v.payload);
  }
}

export function __dynArrayLength(arr: __DynVal): __DynVal {
  const loc = __find(arr.loc);
${p.op("array")}  if (__holdsPayload(loc)) {
    return new __DynVal(arr.payload.length, arr.loc);
  } else {
    return new __DynVal(null, arr.loc);
  }
}
`;
}

/**
 * An empty array. It is an `any[]` like every array at run time
 * (spec §array-operation-code-generation), whatever its element type, so it
 * needs no kind.
 */
const ARRAY_NEW = `export function __dynArrayNew(): __DynVal {
  return __dynUnbound(new Array<any>([]));
}
`;

const ARRAY_APPEND = `export function __dynArrayAppend(arr: __DynVal, v: __DynVal): __DynVal {
  __dynArrayPush(arr, v);
  return arr;
}
`;

// --- §dyn-print --------------------------------------------------------------

/**
 * `print(v)` with `v` at `dyn` (spec §print-typing). It prints where the payload is
 * held, and only looks the location up: printing a value never binds it.
 * `print` is BlueScript's own, supplied from outside (spec §runtime-support-functions).
 */
function dynPrint(p: Probe): string {
  return `export function __dynPrint(v: __DynVal): void {
  const loc = __find(v.loc);
${p.op("print")}  if (__holdsPayload(loc)) {
    print(v.payload);
  }
}
`;
}
