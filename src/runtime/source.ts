import type { BinaryOperator, UnaryOperator } from "../ast/operators.js";
import type { CommKind } from "../ir/projected.js";
import {
  broadcastFunction,
  cloneFunction,
  receiveFunction,
  sendFunction,
} from "../emit/comm.js";
import { ALL_COMM_KINDS } from "./names.js";
import { DYN_BINARY, DYN_UNARY } from "./dyn.js";

/**
 * The BlueScript source of `__runtime_<endpoint>.bs` (spec-dyn.md, sections
 * 6–12): the representation of dynamically located values and the operations
 * on them.
 *
 * Every endpoint gets the same text except for `__here`. It is written only
 * for a program that uses `dyn` (section 7.2). `nothing`, `__and`, `__or` and
 * the communication API are not here; they are supplied from outside, as for
 * every program (spec §runtime-support-functions).
 *
 * Unverified BlueScript behaviour this relies on is listed in section 16 of
 * spec-dyn.md.
 */
export function dynRuntimeSource(endpoint: string): string {
  return [
    `// ChoreoBS dynamic-location runtime for ${endpoint} (spec-dyn.md, sections 6-12).`,
    `// Generated by the compiler; every endpoint's copy differs only in __here.`,
    "",
    LOCATION_VARIABLES,
    LOCATION_ERROR,
    DYN_VALUE,
    locationFunctions(endpoint),
    INJECT_AND_CAST,
    ...BINARY_OPERATORS.map(([operator, source]) => binaryFunction(operator, source)),
    ...UNARY_OPERATORS.map(([operator, source]) => unaryFunction(operator, source)),
    CONVERSIONS,
    COPY_PAYLOAD,
    dispatch(),
    TRANSFER,
    ARRAYS,
  ].join("\n");
}

// --- 6.1 location variables --------------------------------------------------

const LOCATION_VARIABLES = `export class __LocVar {
  parent: __LocVar;
  bound: string;
  rank: integer;

  constructor(bound: string) {
    this.parent = this;
    this.bound = bound;
    this.rank = 0;
  }
}

function __root(v: __LocVar): __LocVar {
  let r: __LocVar = v;
  while (r.parent !== r) {
    r = r.parent;
  }
  return r;
}

export function __find(v: __LocVar): string {
  return __root(v).bound;
}

export function __unify(a: __LocVar, b: __LocVar): string {
  const ra = __root(a);
  const rb = __root(b);
  if (ra === rb) {
    return ra.bound;
  }
  if (ra.bound !== "" && rb.bound !== "") {
    if (ra.bound !== rb.bound) {
      __locationError();
    }
    return ra.bound;
  }
  let top: __LocVar = ra;
  let sub: __LocVar = rb;
  if (rb.bound !== "" || (ra.bound === "" && rb.rank > ra.rank)) {
    top = rb;
    sub = ra;
  }
  sub.parent = top;
  if (sub.rank === top.rank) {
    top.rank = top.rank + 1;
  }
  return top.bound;
}

export function __bind(v: __LocVar, loc: string): void {
  const r = __root(v);
  if (r.bound === "") {
    r.bound = loc;
  } else if (r.bound !== loc) {
    __locationError();
  }
}
`;

// --- 6.2 location error ------------------------------------------------------

// Stops this endpoint for good. Every endpoint adds the same constraints in
// the same order, so every endpoint stops at the same operation. Whether
// BlueScript offers a better way to halt is open (spec-dyn.md, section 16).
const LOCATION_ERROR = `export function __locationError(): void {
  while (true) {
  }
}
`;

// --- 6.3 dynamically located values ------------------------------------------

const DYN_VALUE = `export class __DynVal {
  payload: any;
  loc: __LocVar;

  constructor(payload: any, loc: __LocVar) {
    this.payload = payload;
    this.loc = loc;
  }
}

export function __dynUnbound(payload: any): __DynVal {
  return new __DynVal(payload, new __LocVar(""));
}

export function __dynAt(payload: any, loc: string): __DynVal {
  return new __DynVal(payload, new __LocVar(loc));
}
`;

// --- 6.4 locations -----------------------------------------------------------

function locationFunctions(endpoint: string): string {
  return `export const __here: string = ${JSON.stringify(endpoint)};

export function __isHere(loc: string): boolean {
  return loc === __here;
}

export function __isEvery(loc: string): boolean {
  return loc === "every";
}

export function __isDyn(loc: string): boolean {
  return loc === "dyn";
}

export function __holdsPayload(loc: string): boolean {
  return loc === "" || __isEvery(loc) || __isHere(loc);
}
`;
}

// --- 9. inject and cast -------------------------------------------------------

const INJECT_AND_CAST = `export function __inject(payload: any, loc: string): __DynVal {
  return __dynAt(payload, loc);
}

export function __cast(v: __DynVal, loc: string): any {
  __bind(v.loc, loc);
  if (__isHere(loc) || __isEvery(loc)) {
    return v.payload;
  } else {
    return null;
  }
}
`;

// --- 10. operators -----------------------------------------------------------

/** The operator as written on the two payloads (spec-dyn.md, sections 10.1–10.3). */
const BINARY_OPERATORS: readonly (readonly [BinaryOperator, string])[] = [
  ["+", "left.payload + right.payload"],
  ["-", "left.payload - right.payload"],
  ["*", "left.payload * right.payload"],
  ["/", "left.payload / right.payload"],
  ["%", "left.payload % right.payload"],
  // Both operands are already evaluated, so the short circuit changes nothing.
  ["&&", "left.payload && right.payload"],
  ["||", "left.payload || right.payload"],
  ["<", "left.payload < right.payload"],
  ["<=", "left.payload <= right.payload"],
  [">", "left.payload > right.payload"],
  [">=", "left.payload >= right.payload"],
  ["===", "left.payload === right.payload"],
  ["!==", "left.payload !== right.payload"],
];

const UNARY_OPERATORS: readonly (readonly [UnaryOperator, string])[] = [
  ["!", "!v.payload"],
  ["-", "-v.payload"],
];

function binaryFunction(operator: BinaryOperator, result: string): string {
  return `export function ${DYN_BINARY[operator]}(left: __DynVal, right: __DynVal): __DynVal {
  const loc = __unify(left.loc, right.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal(${result}, left.loc);
  } else {
    return new __DynVal(null, left.loc);
  }
}
`;
}

function unaryFunction(operator: UnaryOperator, result: string): string {
  return `export function ${DYN_UNARY[operator]}(v: __DynVal): __DynVal {
  const loc = __find(v.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal(${result}, v.loc);
  } else {
    return new __DynVal(null, v.loc);
  }
}
`;
}

// --- 10.5 numeric conversion --------------------------------------------------

const CONVERSIONS = `export function __dynIntegerToFloat(v: __DynVal): __DynVal {
  const loc = __find(v.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal((v.payload as integer) as float, v.loc);
  } else {
    return new __DynVal(null, v.loc);
  }
}

export function __dynFloatToInteger(v: __DynVal): __DynVal {
  const loc = __find(v.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal((v.payload as float) as integer, v.loc);
  } else {
    return new __DynVal(null, v.loc);
  }
}
`;

// --- 11. transfer -------------------------------------------------------------

const COPY_PAYLOAD = `function __copyPayload(kind: string, v: any): any {
${ALL_COMM_KINDS.filter(isArrayKind)
  .map(
    (kind, i) =>
      `  ${i === 0 ? "if" : "} else if"} (kind === "${kind}") {\n    return ${cloneFunction(kind)}(v);`,
  )
  .join("\n")}
  } else {
    return v;
  }
}
`;

function isArrayKind(kind: CommKind): boolean {
  return kind.endsWith("Array");
}

/**
 * `__sendAny` / `__receiveAny` / `__broadcastAny`: the communication API chosen
 * by the static `kind` the compiler passes (spec-dyn.md, section 11). The
 * receiving side has no payload to look at, which is why the kind is passed
 * rather than read off the value.
 */
function dispatch(): string {
  const branches = (call: (kind: CommKind) => string): string =>
    ALL_COMM_KINDS.map(
      (kind, i) =>
        `  ${i === 0 ? "if" : "} else if"} (kind === "${kind}") {\n    ${call(kind)}`,
    ).join("\n") +
    `\n  }`;
  return `function __sendAny(to: string, tag: string, kind: string, v: any): void {
${branches((kind) => `${sendFunction(kind)}(to, tag, v);`)}
}

function __receiveAny(from: string, tag: string, kind: string): any {
${branches((kind) => `return ${receiveFunction(kind)}(from, tag);`)}
  return null;
}

function __broadcastAny(tag: string, kind: string, v: any): void {
${branches((kind) => `${broadcastFunction(kind)}(tag, v);`)}
}
`;
}

const TRANSFER = `export function __dynTransfer(tag: string, kind: string, to: string, v: __DynVal): __DynVal {
  const from = __find(v.loc);
  if (from === "" || __isEvery(from)) {
    if (__isDyn(to)) {
      return __dynUnbound(__copyPayload(kind, v.payload));
    } else if (__isEvery(to) || __isHere(to)) {
      return __dynAt(__copyPayload(kind, v.payload), to);
    } else {
      return __dynAt(null, to);
    }
  } else if (__isHere(from)) {
    if (__isDyn(to)) {
      __broadcastAny(tag, kind, v.payload);
      return __dynUnbound(__copyPayload(kind, v.payload));
    } else if (__isEvery(to)) {
      __broadcastAny(tag, kind, v.payload);
      return __dynAt(__copyPayload(kind, v.payload), to);
    } else if (__isHere(to)) {
      return __dynAt(__copyPayload(kind, v.payload), to);
    } else {
      __sendAny(to, tag, kind, v.payload);
      return __dynAt(null, to);
    }
  } else {
    if (__isDyn(to)) {
      return __dynUnbound(__receiveAny(from, tag, kind));
    } else if (__isEvery(to) || __isHere(to)) {
      return __dynAt(__receiveAny(from, tag, kind), to);
    } else {
      return __dynAt(null, to);
    }
  }
}
`;

// --- 12. arrays ----------------------------------------------------------------

const ARRAYS = `export function __dynArrayGet(arr: __DynVal, i: __DynVal): __DynVal {
  const loc = __unify(arr.loc, i.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal(arr.payload[i.payload], arr.loc);
  } else {
    return new __DynVal(null, arr.loc);
  }
}

export function __dynArraySet(arr: __DynVal, i: __DynVal, v: __DynVal): void {
  __unify(arr.loc, i.loc);
  const loc = __unify(i.loc, v.loc);
  if (__holdsPayload(loc)) {
    arr.payload[i.payload] = v.payload;
  }
}

export function __dynArrayPush(arr: __DynVal, v: __DynVal): void {
  const loc = __unify(arr.loc, v.loc);
  if (__holdsPayload(loc)) {
    arr.payload.push(v.payload);
  }
}

export function __dynArrayLength(arr: __DynVal): __DynVal {
  const loc = __find(arr.loc);
  if (__holdsPayload(loc)) {
    return new __DynVal(arr.payload.length, arr.loc);
  } else {
    return new __DynVal(null, arr.loc);
  }
}

export function __dynArrayNew(kind: string): __DynVal {
  if (kind === "integerArray") {
    const a: integer[] = [];
    return __dynUnbound(a);
  } else if (kind === "floatArray") {
    const a: float[] = [];
    return __dynUnbound(a);
  } else {
    const a: boolean[] = [];
    return __dynUnbound(a);
  }
}

export function __dynArrayAppend(arr: __DynVal, v: __DynVal): __DynVal {
  __dynArrayPush(arr, v);
  return arr;
}
`;
